#!/usr/bin/env python3
"""Converts the owner-supplied NIGHTLINK logo (art/ansi/source/nightlink-logo-owner.webp) to VGA pixel art.

Crops the artwork, reduces it to a 240 x 39 pixel grid with a box filter, maps every pixel to the nearest of the
16 VGA colors without dithering, and writes:
  terminal-logo-art.js          in-app data module (rows of hex palette indices), drawn by terminal-logo.js
  art/ansi/nightlink-logo-v2.ans        CP437 half-block ANSI, 240 columns, classic SGR (no iCE colors)
  art/ansi/nightlink-logo-v2-80.ans     CP437 half-block ANSI reduced to 80 columns
  art/ansi/nightlink-logo-v2.png        preview of the pixel grid at 4x
Requires Pillow. Usage: python3 art/ansi/make-logo-art.py
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'art', 'ansi', 'source', 'nightlink-logo-owner.webp')
CROP = (39, 146, 1968, 463)  # artwork bounds in the source image
VGA = [(0, 0, 0), (0, 0, 170), (0, 170, 0), (0, 170, 170), (170, 0, 0), (170, 0, 170), (170, 85, 0), (170, 170, 170),
       (85, 85, 85), (85, 85, 255), (85, 255, 85), (85, 255, 255), (255, 85, 85), (255, 85, 255), (255, 255, 85), (255, 255, 255)]
FG = ['30', '34', '32', '36', '31', '35', '33', '37', '1;30', '1;34', '1;32', '1;36', '1;31', '1;35', '1;33', '1;37']
BG = ['40', '44', '42', '46', '41', '45', '43', '47']  # VGA index 0-7 -> ANSI background (ANSI order differs)
CP437 = {'█': 0xDB, '▀': 0xDF, '▄': 0xDC}


def grid(width):
    im = Image.open(SRC).convert('RGB').crop(CROP)
    height = round(im.height * width / im.width)
    small = im.resize((width, height), Image.BOX)
    pal = Image.new('P', (1, 1))
    flat = [c for t in VGA for c in t]
    pal.putpalette(flat + [0] * (768 - len(flat)))
    q = small.quantize(palette=pal, dither=Image.Dither.NONE)
    return q, [[q.getpixel((x, y)) for x in range(width)] for y in range(height)]


def ansi(rows):
    """Two pixel rows per text row with half blocks. Backgrounds are limited to colors 0-7; a bright lower pixel
    under a normal upper pixel is drawn as a lower half block instead."""
    if len(rows) % 2:
        rows = rows + [[0] * len(rows[0])]
    out = []
    for y in range(0, len(rows), 2):
        line = ''
        for top, bot in zip(rows[y], rows[y + 1]):
            if top == bot:
                line += ('\x1b[0m ' if top == 0 else f'\x1b[0;{FG[top]}m█')
            elif bot == 0:
                line += f'\x1b[0;{FG[top]}m▀'
            elif top == 0:
                line += f'\x1b[0;{FG[bot]}m▄'
            elif bot < 8:
                line += f'\x1b[0;{FG[top]};{BG[bot]}m▀'
            elif top < 8:
                line += f'\x1b[0;{FG[bot]};{BG[top]}m▄'
            else:
                line += f'\x1b[0;{FG[top]};{BG[bot - 8]}m▀'  # both bright: nearest normal background
        out.append(line + '\x1b[0m')
    return '\r\n'.join(out) + '\r\n'


def cp437(text):
    return bytes(CP437.get(ch, ord(ch)) for ch in text)


def main():
    q, rows = grid(240)
    with open(os.path.join(ROOT, 'terminal-logo-art.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by art/ansi/make-logo-art.py from art/ansi/source/nightlink-logo-owner.webp. Do not edit.\n'
                '   NIGHTLINK logo as 240 x 39 VGA pixels; each character is a palette index 0-f (0 = black / transparent). */\n')
        f.write('(function(root){const art={width:240,height:%d,rows:[\n' % len(rows))
        f.write(',\n'.join("'" + ''.join('%x' % v for v in r) + "'" for r in rows))
        f.write("]};if(typeof module==='object'&&module.exports)module.exports=art;else root.NightlinkLogoArt=art;})(typeof window==='object'?window:globalThis);\n")
    q.convert('RGB').resize((240 * 4, len(rows) * 4), Image.NEAREST).save(os.path.join(ROOT, 'art', 'ansi', 'nightlink-logo-v2.png'))
    with open(os.path.join(ROOT, 'art', 'ansi', 'nightlink-logo-v2.ans'), 'wb') as f:
        f.write(cp437(ansi(rows)))
    _, rows80 = grid(80)
    with open(os.path.join(ROOT, 'art', 'ansi', 'nightlink-logo-v2-80.ans'), 'wb') as f:
        f.write(cp437(ansi(rows80)))


if __name__ == '__main__':
    main()
