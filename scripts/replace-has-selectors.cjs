/* One-time conversion (#207): replaces CSS :has() selectors with state classes maintained by has-state.js.
   Ancestor-anchored :has() rules made Chromium restyle the whole document on every DOM insertion. */
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const files=fs.readdirSync(root).filter(f=>f.endsWith('.css'));
const entries=new Map();// key anchor|arg -> class
function close(s,i,loose){let d=0;for(;i<s.length;i++){if(s[i]==='(')d++;else if(s[i]===')'){d--;if(!d)return i;}}if(loose)return s.length;throw Error('unbalanced');}
function anchorBefore(s,k){// outermost compound selector that contains position k
 let start=Math.max(s.lastIndexOf('{',k),s.lastIndexOf('}',k),s.lastIndexOf(';',k))+1,d=0,compound=start;
 for(let i=start;i<k;i++){const c=s[i];if(c==='(')d++;else if(c===')')d--;else if(d===0&&/[\s>+~,]/.test(c))compound=i+1;}
 let a=s.slice(compound,k);
 for(;;){const m=a.search(/:(has|is|not|where)\(/);if(m<0)break;const e=close(a,a.indexOf('(',m),true);a=a.slice(0,m)+a.slice(e+1);}
 a=a.replace(/::?[\w-]+$/,'').replace(/:(hover|focus-visible|focus-within|focus|active|disabled)/g,'');
 return a||'*';}
let total=0;const out=[];
for(const f of files){const p=path.join(root,f);let s=fs.readFileSync(p,'utf8');if(!s.includes(':has('))continue;let n=0;
 for(;;){const k=s.indexOf(':has(');if(k<0)break;const e=close(s,k+4);const arg=s.slice(k+5,e).trim(),anchor=anchorBefore(s,k).trim();
  const key=anchor+'|'+arg;if(!entries.has(key))entries.set(key,'nlh-'+entries.size);s=s.slice(0,k)+'.'+entries.get(key)+s.slice(e+1);n++;}
 out.push([p,s]);total+=n;console.log(f,n);}
for(const [p,s] of out)fs.writeFileSync(p,s);
const list=[...entries].map(([k,c])=>{const i=k.indexOf('|');return [c,k.slice(0,i),k.slice(i+1)];});
fs.writeFileSync(path.join(root,'has-state-rules.js'),'/* Generated by scripts/replace-has-selectors.cjs: [class, anchor selector, :has() argument]. */\nwindow.NightlinkHasRules='+JSON.stringify(list,null,0).replace(/\],\[/g,'],\n[')+';\n');
console.log('total',total,'unique',list.length);
